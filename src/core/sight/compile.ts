import { B, C, I, P2, P3, P4, R, T, block, comment, param, type BlkBlock, type BlkNode } from '../blk/types';
import { validateSightText, type ValidationReport } from '../blk/validate';
import { writeBlk } from '../blk/writer';
import { FILE_NAME_RE, VEHICLE_FOLDER_RE, type ElementsConfig, type Prim, type SightGlobals } from './model';

export interface CompileInput {
  globals: SightGlobals;
  elements: ElementsConfig;
  prims: Prim[];
  /** Shown in the header comment. */
  generator?: string;
  date?: Date;
}

export interface CompileResult {
  text: string;
  fileName: string;
  installPath: string;
  report: ValidationReport;
  /** Problems with the configuration itself (before writing). */
  configErrors: string[];
  bytes: number;
}

/** Native range-scale notches: label = hundreds of metres on every `labelEvery` metres, 0 = notch only. */
export function distanceList(dt: ElementsConfig['distanceTicks']): [number, number][] {
  const out: [number, number][] = [];
  if (dt.step <= 0) return out;
  for (let d = dt.step; d <= dt.maxDistance + 1e-6; d += dt.step) {
    const label = dt.labelEvery > 0 && d % dt.labelEvery === 0 ? Math.round(d / 100) : 0;
    out.push([d, label]);
  }
  return out;
}

export function checkConfig(g: SightGlobals, prims: Prim[]): string[] {
  const errs: string[] = [];
  if (!FILE_NAME_RE.test(g.fileName)) errs.push('fileName');
  if (!VEHICLE_FOLDER_RE.test(g.folder)) errs.push('folder');
  if (g.folder === 'all_tanks' && !Object.values(g.matchClasses).some(Boolean)) errs.push('matchClasses');
  for (const p of prims) {
    const nums =
      p.kind === 'line' ? [...p.a, ...p.b] : p.kind === 'quad' ? p.p.flat() : p.kind === 'circle' ? [...p.pos, p.diameter, p.size] : [...p.pos, p.size];
    if (nums.some((n) => !Number.isFinite(n))) {
      errs.push('nonFinite');
      break;
    }
  }
  if (prims.length === 0) errs.push('empty');
  return errs;
}

const yes = B(true);
const no = B(false);

function primBlocks(prims: Prim[]) {
  const lines: BlkNode[] = [];
  const quads: BlkNode[] = [];
  const circles: BlkNode[] = [];
  const texts: BlkNode[] = [];
  for (const p of prims) {
    switch (p.kind) {
      case 'line':
        lines.push(block('line', [param('line', P4(p.a[0], p.a[1], p.b[0], p.b[1])), param('move', no), param('thousandth', yes)], { inline: true }));
        break;
      case 'quad': {
        const [tl, tr, br, bl] = p.p;
        quads.push(
          block('quad', [param('tl', P2(...tl)), param('tr', P2(...tr)), param('br', P2(...br)), param('bl', P2(...bl)), param('thousandth', yes)], { inline: true }),
        );
        break;
      }
      case 'circle':
        circles.push(
          block(
            'circle',
            [
              param('segment', P2(p.segment[0], p.segment[1])),
              param('pos', P2(...p.pos)),
              param('diameter', R(p.diameter)),
              param('size', R(p.size)),
              param('move', no),
              param('thousandth', yes),
            ],
            { inline: true },
          ),
        );
        break;
      case 'text':
        texts.push(
          block(
            'text',
            [
              param('text', T(p.text)),
              param('align', I(p.align)),
              param('pos', P2(...p.pos)),
              param('move', no),
              param('thousandth', yes),
              param('size', R(p.size)),
              param('highlight', yes),
            ],
            { inline: true },
          ),
        );
        break;
    }
  }
  return { lines, quads, circles, texts };
}

export function compileSight({ globals: g, elements: el, prims, generator = 'WT Sight Forge', date = new Date() }: CompileInput): CompileResult {
  const configErrors = checkConfig(g, prims);
  const dt = el.distanceTicks;
  const top: BlkNode[] = [
    comment(`Generated by ${generator} - ${date.toISOString().slice(0, 10)} - https://wilberods-coder.github.io/wt-sight-forge/`),
    comment(`Install: UserSights/${g.folder}/${g.fileName}.blk`),
    comment('Coordinates are in thousandths (mils), y axis points down.'),
    param('thousandth', T(g.thousandth)),
    param('crosshairColor', C(...g.color)),
    param('crosshairLightColor', C(...g.lightColor)),
    param('lineSizeMult', R(g.lineSizeMult)),
    param('fontSizeMult', R(g.fontSizeMult)),
    // The default crosshair is replaced by our own elements.
    param('drawCentralLineVert', no),
    param('drawCentralLineHorz', no),
    param('crosshairHorVertSize', P2(0, 0)),
    // Rangefinder progress bar: values from the official wiki example.
    param('rangefinderProgressBarColor1', C(0, 255, 0, 64)),
    param('rangefinderProgressBarColor2', C(255, 255, 255, 64)),
    param('rangefinderTextScale', R(0.7)),
    param('rangefinderVerticalOffset', R(15)),
    param('rangefinderHorizontalOffset', R(5)),
    param('drawDistanceCorrection', B(g.drawDistanceCorrection)),
    param('distanceCorrectionPos', P2(-0.26, -0.05)),
    param('crosshairDistHorSizeMain', P2(dt.enabled ? dt.tickLength : 0, dt.enabled ? dt.tickLength * 0.5 : 0)),
    param('crosshairDistHorSizeAdditional', P2(0.005, 0.003)),
  ];
  if (dt.enabled) top.push(param('drawUpward', B(dt.drawUpward)), param('distancePos', P2(dt.posX, 0)));

  const blocks: BlkBlock[] = [];
  if (g.folder === 'all_tanks')
    blocks.push(
      block(
        'matchExpClass',
        Object.entries(g.matchClasses).map(([k, v]) => param(k, B(v))),
      ),
    );
  blocks.push(block('crosshair_distances', dt.enabled ? distanceList(dt).map(([d, l]) => param('distance', P3(d, l, 0))) : []));
  blocks.push(block('crosshair_hor_ranges', []));

  const pb = primBlocks(prims);
  if (pb.lines.length) blocks.push(block('drawLines', pb.lines));
  if (pb.quads.length) blocks.push(block('drawQuads', pb.quads));
  if (pb.circles.length) blocks.push(block('drawCircles', pb.circles));
  if (pb.texts.length) blocks.push(block('drawTexts', pb.texts));

  const text = writeBlk({ children: [...top, ...blocks] });
  const report = validateSightText(text);
  return {
    text,
    fileName: `${g.fileName}.blk`,
    installPath: `UserSights/${g.folder}/${g.fileName}.blk`,
    report,
    configErrors,
    bytes: new TextEncoder().encode(text).length,
  };
}

/**
 * Rough drop angle (mils) of a shell at `distance` metres, vacuum trajectory.
 * Used only to place the game's native range notches in the browser preview —
 * in-game the notches come from the real ballistics of the loaded shell.
 */
export function approxDropMils(distance: number, speed: number, milsPerRad: number): number {
  const t = distance / speed;
  const drop = 0.5 * 9.81 * t * t;
  return (drop / distance) * milsPerRad;
}
